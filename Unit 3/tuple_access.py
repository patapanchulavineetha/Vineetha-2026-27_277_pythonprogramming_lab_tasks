# Create a tuple
my_tuple = (10, 20, 30, 40, 50)

# Display the tuple
print("Tuple:", my_tuple)

# Access elements
print("First element:", my_tuple[0])
print("Second element:", my_tuple[1])
print("Last element:", my_tuple[-1])

# Traverse the tuple
print("Tuple elements:")
for element in my_tuple:
    print(element)
